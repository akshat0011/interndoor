/**
 * The weekly DATA posts — LinkedIn drafts made only of counts from the store.
 *
 * WHY. A hand-drafted "10 employers that posted the most engineering
 * internships in India since July" took 8,395 impressions in a day on
 * 17 Sep 2026 — twice what the personal account does in its best measured
 * WEEK (§12). The format is a ranked list with real numbers, one link and no
 * sell, and every number in it already exists in the store. This makes that
 * a standing weekly draft rather than an afternoon's spreadsheet.
 *
 * SEVEN FORMATS, ONE WINDOW. Each is a different cut of the same rows — the
 * last `WINDOW_DAYS` on one board — so the numbers move week to week and the
 * post never repeats itself. All seven are written to one page with a card
 * image each; `pickOfWeek` names one so the page has an answer to "which",
 * and he can ignore it.
 *
 * THE RULES ARE /report's (§11): every number carries its denominator, a
 * count too thin to say anything is DROPPED rather than weakened, nothing is
 * generated by a model, and the sources are never named — the post says
 * "we tracked", never where. "Stated a stipend" is the site's own
 * `stipendText` rule over the published projection: `₹0` and a bare number
 * are not a stipend. Employers are those on TODAY's watchlist, re-derived
 * through `matchCompany` exactly as publish does — the stored
 * `company_matched` column is what the row matched when it was stored, and
 * a 15 Sep draft counted STEMpedia's 13 postings that way after the employer
 * had been de-listed.
 *
 * FULL-TIME GRADUATE ROLES ARE OUT. They are collected on purpose and the
 * board files them under their own tab, but a post that says "internships"
 * and counts them is the "Campus … (Full-Time)" mistake of 15 Sep again.
 */
