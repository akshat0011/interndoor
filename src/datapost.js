function link(cfg, region, path, content) {
  return utmUrl(`${SITE}${regionPath(region)}${path}`, { campaign: CAMPAIGN, content, source: 'linkedin', medium: 'social' }, cfg);
}
const placeName = (region) => regionOf(region)?.name ?? region;
const hashtags = (...t) => t.map((x) => `#${x}`).join(' ');

/** 1. Who posted the most. */
export function employersPost(data, cfg) {
  const { rows, region, days } = data;
  if (rows.length < MIN_ROWS) return null;
  const by = new Map();
  const titles = new Map();
  for (const r of rows) {
    by.set(r.employer, (by.get(r.employer) ?? 0) + 1);
    if (!titles.has(r.employer)) titles.set(r.employer, new Set());
    titles.get(r.employer).add(r.title.toLowerCase());
  }
  const top = sortDesc(by).slice(0, 10);
  if (top.length < 5) return null;
  const where = placeName(region);
  const head = `The ${top.length} employers that posted the most engineering internships in ${where} in the last ${days} days:`;
  const lines = top.map(([c, n], i) => `${i + 1}. ${c} — ${n}`);
  const multi = top.filter(([c, n]) => n > titles.get(c).size).length;
  const post = [
    boldSans(head), '',
    ...lines, '',
    multi
      ? `Some of these post the same role in several cities, so ${top[0][1]} postings isn't ${top[0][1]} different jobs. But it does tell you who is actively taking interns right now.`
      : 'It tells you who is actively taking interns right now.',
    '',
    `Every one of them has a page showing what they've posted, month by month, and whether they ever stated pay:`,
    link(cfg, region, '/companies', 'employers'),
    '',
    hashtags('internships', 'hiring', 'engineering', 'placements'),
  ].join('\n');
  return {
    key: 'employers',
    title: `Who's hiring: the ${top.length} busiest employers`,
    post,
    stats: { rows: rows.length, employers: by.size, listed: top.length, top: top.map(([c, n]) => ({ employer: c, postings: n, titles: titles.get(c).size })) },
    notes: `${rows.length} internships from ${by.size} employers in the window. Ties break alphabetically. ${multi} of the ${top.length} post more roles than they have distinct titles.`,
    card: {
      eyebrow: `${where} · last ${days} days`,
      headline: `Who's hiring the most engineering interns`,
      rows: top.map(([c, n]) => ({ label: c, value: String(n), share: n / top[0][1] })),
      band: 'BE EARLY.',
    },
  };
}

/** 2. Who posted for the FIRST time. */
export function newcomersPost(data, cfg) {
  const { rows, history, region, days, since, trackedSince } = data;
  if (rows.length < MIN_ROWS) return null;
  const before = new Set(history.filter((r) => r.firstSeen <= since).map((r) => r.employer));
  const by = new Map();
  for (const r of rows) if (!before.has(r.employer)) by.set(r.employer, (by.get(r.employer) ?? 0) + 1);
  const fresh = sortDesc(by);
  if (fresh.length < 8) return null;
  const listed = fresh.slice(0, 12);
  const where = placeName(region);
  const startMonth = trackedSince ? new Date(trackedSince).toLocaleString('en-GB', { month: 'long', timeZone: regionOf(region)?.timeZone ?? 'Asia/Kolkata' }) : null;
  const head = `${fresh.length} employers posted their first engineering internship in ${where} in the last ${days} days.`;
  const post = [
    boldSans(head), '',
    `First since we started tracking${startMonth ? ` in ${startMonth}` : ''}, that is — not first ever. But if you've been refreshing the same five careers pages, these are the ones you're not watching:`,
    '',
    ...listed.map(([c, n]) => `→ ${c}${n > 1 ? ` (${n})` : ''}`),
    fresh.length > listed.length ? `…and ${fresh.length - listed.length} more.` : '',
    '',
    `All ${fresh.length} are on the board, each with a page of what they've posted:`,
    link(cfg, region, '/companies', 'newcomers'),
    '',
    hashtags('internships', 'hiring', 'engineeringstudents', 'placements'),
  ].filter((l, i, a) => !(l === '' && a[i - 1] === '')).join('\n');
  return {
    key: 'newcomers',
    title: `${fresh.length} employers hiring interns for the first time`,
    post,
    stats: { rows: rows.length, newcomers: fresh.length, listed: listed.map(([c, n]) => ({ employer: c, postings: n })), trackedSince },
    notes: `A newcomer has no row on the board before the window opened (${new Date(since).toISOString().slice(0, 10)}); tracking began ${trackedSince ? new Date(trackedSince).toISOString().slice(0, 10) : '—'}. Listed by postings in the window, then name.`,
    card: {
      eyebrow: `${where} · last ${days} days`,
      headline: `${fresh.length} employers posted their first internship here`,
      rows: listed.slice(0, 10).map(([c, n]) => ({ label: c, value: n > 1 ? String(n) : '', share: n / listed[0][1] })),
      band: 'NEW THIS MONTH.',
    },
  };
}

/** 3. How fast the queue forms. */
export function queuePost(data, cfg) {
  const { rows, region, days } = data;
  /* dataRows already gives a careers-board row no count — the guard lives
     there, once, where the annotation is made. */
  const counted = rows.filter((r) => r.applicants != null);
  if (counted.length < MIN_COUNTED) return null;
  const bands = { none: 0, few: 0, some: 0, many: 0 };
  for (const r of counted) {
    if (r.applicants === 0) bands.none += 1;
    else if (r.applicants < 25) bands.few += 1;
    else if (r.applicants < 100) bands.some += 1;
    else bands.many += 1;
  }
  const n = counted.length;
  const oneIn = ratio(bands.many, n);
  const where = placeName(region);
  const head = oneIn
    ? `1 in ${oneIn} engineering internships in ${where} had 100+ applicants within hours of going up.`
    : `Most engineering internships in ${where} still had a short queue when we found them.`;
  const wa = whatsappFor(region, cfg);
  const tg = telegramFor(region, cfg);
  const post = [
    boldSans(head), '',
    `We see most postings within a few hours of them going live. Of the ${n} we counted in the last ${days} days, at that moment:`,
    '',
    `👥 100+ applicants — ${bands.many} (${pct(bands.many, n)}%)`,
    `👥 25 to 99 — ${bands.some} (${pct(bands.some, n)}%)`,
    `👥 1 to 24 — ${bands.few} (${pct(bands.few, n)}%)`,
    `👥 Nobody yet — ${bands.none} (${pct(bands.none, n)}%)`,
    '',
    `${pct(bands.none + bands.few, n)}% had under 25 applicants. That is the window. It closes in a day.`,
    '',
    wa ? `Every new role, the minute it's listed → ${wa.url}` : (tg ? `Every new role, the minute it's listed → ${tg.url}` : null),
    `The board → ${link(cfg, region, '/', 'queue')}`,
    '',
    hashtags('internships', 'jobsearch', 'freshers', 'engineering'),
  ].filter((l) => l !== null).join('\n');
  return {
    key: 'queue',
    title: 'How fast the queue forms',
    post,
    stats: { counted: n, bands, cutoffs: { many: 100, some: 25 }, oneIn, pct: { many: pct(bands.many, n), some: pct(bands.some, n), few: pct(bands.few, n), none: pct(bands.none, n), under25: pct(bands.none + bands.few, n) } },
    notes: `Applicant counts are the posting's own figure at FIRST sighting, never refreshed; careers-board rows carry none and are excluded. "Over 100" counts as 100+.`,
    card: {
      eyebrow: `${where} · last ${days} days · ${n} postings`,
      headline: oneIn ? `1 in ${oneIn} had 100+ applicants within hours` : 'The queue forms in a day',
      rows: [
        { label: '100+ applicants', value: `${pct(bands.many, n)}%`, share: bands.many / n },
        { label: '25 – 99', value: `${pct(bands.some, n)}%`, share: bands.some / n },
        { label: '1 – 24', value: `${pct(bands.few, n)}%`, share: bands.few / n },
        { label: 'Nobody yet', value: `${pct(bands.none, n)}%`, share: bands.none / n },
      ],
      band: 'BE EARLY.',
    },
  };
}

/** 4. Who says what they pay. */
export function stipendsPost(data, cfg) {
  const { rows, region, days } = data;
  if (rows.length < MIN_ROWS) return null;
  const stated = rows.filter((r) => r.stated);
  const by = new Map();
  for (const r of rows) by.set(r.employer, (by.get(r.employer) ?? 0) + 1);
  const top = sortDesc(by).slice(0, 10);
  const topStated = top.filter(([c]) => rows.some((r) => r.employer === c && r.stated)).length;
  const topPostings = top.reduce((s, [, n]) => s + n, 0);
  const monthly = rows.map((r) => r.monthlyInr).filter((v) => v != null).sort((a, b) => a - b);
  const median = monthly.length >= 5 ? monthly[Math.floor(monthly.length / 2)] : null;
  const oneIn = ratio(stated.length, rows.length);
  const where = placeName(region);
  const head = `Only ${stated.length} of ${rows.length} engineering internships in ${where} stated a stipend in the last ${days} days.`;
  const post = [
    boldSans(head), '',
    oneIn ? `About 1 in ${oneIn}.` : 'None.', '',
    `The ${top.length} employers that posted the most — ${top.slice(0, 5).map(([c]) => c).join(', ')} and ${top.length - 5} more — posted ${topPostings} between them. ${topStated === 0 ? 'Not one listing carried a figure.' : `${topStated} of them stated pay on at least one listing.`}`,
    '',
    `That doesn't mean they don't pay — most do. It means you usually find out after the interview, not before you apply.`,
    median ? `\nWhere a monthly figure was stated (${monthly.length} listings), the middle one was ₹${median.toLocaleString('en-IN')}.` : '',
    '',
    `→ Ask about the stipend on the first HR call, not after the offer.`,
    `→ Check an employer's hiring record before you apply — every company page shows whether it has ever stated pay:`,
    link(cfg, region, '/companies', 'stipends'),
    '',
    hashtags('internships', 'engineeringstudents', 'stipend', 'placements'),
  ].filter((l, i, a) => !(l === '' && a[i - 1] === '')).join('\n');
  return {
    key: 'stipends',
    title: 'Who says what they pay',
    post,
    stats: { rows: rows.length, stated: stated.length, oneIn, top: top.length, topPostings, topStated, monthlyFigures: monthly.length, medianMonthlyInr: median },
    notes: `"Stated" is the site's own stipendText rule over the published projection: ₹0, a bare number and a missing period are not a stipend. Median is over INR monthly minimums only.`,
    card: {
      eyebrow: `${where} · last ${days} days`,
      headline: `${stated.length} of ${rows.length} internships stated a stipend`,
      rows: [
        { label: 'Stated a stipend', value: `${pct(stated.length, rows.length)}%`, share: stated.length / rows.length },
        { label: 'Did not', value: `${pct(rows.length - stated.length, rows.length)}%`, share: (rows.length - stated.length) / rows.length },
        ...(median ? [{ label: 'Median monthly, where stated', value: `₹${median.toLocaleString('en-IN')}`, share: 0 }] : []),
      ],
      band: 'ASK EARLY.',
    },
  };
}

/** 5. When they go up. */
export function timingPost(data, cfg) {
  const { rows, region, days } = data;
  const zone = regionOf(region)?.timeZone ?? 'Asia/Kolkata';
  const live = rows.filter((r) => !r.ats && r.postedAt);
  if (live.length < MIN_COUNTED) return null;
  const DAYS = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
  const byDay = new Array(7).fill(0);
  const byBlock = { morning: 0, afternoon: 0, evening: 0, night: 0 };
  for (const r of live) {
    const local = new Date(new Date(r.postedAt).toLocaleString('en-US', { timeZone: zone }));
    byDay[local.getDay()] += 1;
    const h = new Date(new Date(r.firstSeen).toLocaleString('en-US', { timeZone: zone })).getHours();
    if (h >= 6 && h < 12) byBlock.morning += 1;
    else if (h >= 12 && h < 18) byBlock.afternoon += 1;
    else if (h >= 18) byBlock.evening += 1;
    else byBlock.night += 1;
  }
  const n = live.length;
  const ranked = DAYS.map((d, i) => [d, byDay[i]]).sort((a, b) => b[1] - a[1]);
  const weekend = byDay[0] + byDay[6];
  const block = Object.entries(byBlock).sort((a, b) => b[1] - a[1])[0];
  const blockLabel = { morning: '6 am and noon', afternoon: 'noon and 6 pm', evening: '6 pm and midnight', night: 'midnight and 6 am' }[block[0]];
  const where = placeName(region);
  const head = `${ranked[0][0]} is when engineering internships in ${where} go up.`;
  const post = [
    boldSans(head), '',
    `Of the ${n} we caught within hours of being posted in the last ${days} days:`,
    '',
    `📅 ${ranked[0][0]} — ${ranked[0][1]}. ${ranked[1][0]} and ${ranked[2][0]} next (${ranked[1][1]} and ${ranked[2][1]}).`,
    `📅 Saturday and Sunday together — ${weekend}. ${weekend ? `About 1 in ${ratio(weekend, n)}.` : ''}`.trim(),
    `🕐 ${pct(block[1], n)}% appeared between ${blockLabel}.`,
    '',
    `So if you check once a day, check ${block[0] === 'evening' ? 'in the evening' : block[0] === 'afternoon' ? 'after lunch' : `in the ${block[0]}`}, ${ranked[0][0]} to ${ranked[2][0]}.`,
    '',
    `Or don't check at all — every new role goes out the minute it's listed:`,
    link(cfg, region, '/alerts', 'timing'),
    '',
    hashtags('internships', 'jobsearch', 'freshers', 'engineering'),
  ].join('\n');
  return {
    key: 'timing',
    title: 'When internships go up',
    post,
    stats: { counted: n, byDay: Object.fromEntries(DAYS.map((d, i) => [d, byDay[i]])), weekend, weekendOneIn: ratio(weekend, n), byBlock, blockPct: pct(block[1], n) },
    notes: `Weekday from the posting's own date in ${zone}; hour block from first sighting (the sweep window is ~3 h, so read it as "within a few hours of"). Careers-board rows are excluded: their first-sighting time is the poll, not the posting.`,
    card: {
      eyebrow: `${where} · last ${days} days · ${n} postings`,
      headline: `When internships go up`,
      rows: DAYS.slice(1).concat(DAYS.slice(0, 1)).map((d) => ({ label: d, value: String(byDay[DAYS.indexOf(d)]), share: byDay[DAYS.indexOf(d)] / (ranked[0][1] || 1) })),
      band: 'CHECK ' + (block[0] === 'afternoon' ? 'AFTER LUNCH.' : block[0].toUpperCase() + 'S.'),
    },
  };
}

/** 6. Where they are. */
export function citiesPost(data, cfg) {
  const { rows, region, days } = data;
  if (rows.length < MIN_ROWS) return null;
  const by = new Map();
  for (const r of rows) if (r.city) by.set(r.city, (by.get(r.city) ?? 0) + 1);
  const top = sortDesc(by).slice(0, 6);
  if (top.length < 4) return null;
  const modes = { onsite: 0, hybrid: 0, remote: 0 };
  for (const r of rows) if (r.mode in modes) modes[r.mode] += 1;
  const n = rows.length;
  const where = placeName(region);
  const head = `${pct(top[0][1], n)}% of engineering internships in ${where} are in ${top[0][0]}. ${pct(modes.remote, n)}% are remote.`;
  const post = [
    boldSans(head), '',
    `Of the ${n} we tracked in the last ${days} days:`,
    '',
    ...top.map(([c, k]) => `📍 ${c} — ${k}${k === top[0][1] ? ` (${pct(k, n)}%)` : ''}`),
    '',
    `And how:`,
    `🏢 On-site — ${pct(modes.onsite, n)}%`,
    `🔀 Hybrid — ${pct(modes.hybrid, n)}%`,
    `🏠 Remote — ${pct(modes.remote, n)}%`,
    '',
    `If you're holding out for a remote engineering internship, the numbers say widen the search. If you can move to ${top[0][0]} for six months, that's ${pct(top[0][1], n) >= 40 ? 'close to half' : 'the biggest slice of'} the market.`,
    '',
    `Browse by city → ${link(cfg, region, '/locations', 'cities')}`,
    '',
    hashtags('internships', top[0][0].toLowerCase().replace(/[^a-z]/g, ''), 'engineeringstudents', 'placements'),
  ].join('\n');
  return {
    key: 'cities',
    title: 'Where the internships are',
    post,
    stats: { rows: n, cities: top.map(([c, k]) => ({ city: c, postings: k, pct: pct(k, n) })), modes, modePct: { onsite: pct(modes.onsite, n), hybrid: pct(modes.hybrid, n), remote: pct(modes.remote, n) }, modeStated: modes.onsite + modes.hybrid + modes.remote },
    notes: `City by the site's canonicalCity fold (Bengaluru/Bangalore, Gurugram/Gurgaon). Mode percentages are over ALL ${n} rows; ${n - (modes.onsite + modes.hybrid + modes.remote)} state none.`,
    card: {
      eyebrow: `${where} · last ${days} days · ${n} postings`,
      headline: `Where the internships are`,
      rows: top.map(([c, k]) => ({ label: c, value: `${pct(k, n)}%`, share: k / top[0][1] })),
      band: `${pct(modes.remote, n)}% REMOTE.`,
    },
  };
}

