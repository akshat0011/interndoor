export const WINDOW_DAYS = 30;
/* Below these the sentence is not a finding. Dropped, not weakened. */
export const MIN_ROWS = 40;
export const MIN_COUNTED = 30;
export const FORMATS = ['employers', 'newcomers', 'queue', 'stipends', 'timing', 'cities', 'skills', 'spotlight'];
export const CAMPAIGN = 'data-post';

const pct = (n, of) => (of ? Math.round((100 * n) / of) : 0);
const ratio = (n, of) => (n > 0 ? Math.max(2, Math.round(of / n)) : null);
const sortDesc = (m) => [...m].sort((a, b) => b[1] - a[1] || String(a[0]).localeCompare(String(b[0])));

/**
 * The board's engineering internships, annotated, split into the window and
 * the whole history. History is what "first time" means: the earliest row on
 * the board is when tracking began, and a newcomer is an employer with no row
 * before the window.
 */
export function dataRows(store, cfg, { region = 'IN', now = Date.now(), days = WINDOW_DAYS } = {}) {
  const code = String(region).toUpperCase();
  const since = now - days * 86_400_000;
  const raw = store.db.prepare('SELECT * FROM jobs WHERE is_tech = 1 AND suppressed_reason IS NULL').all();
  const history = [];
  for (const r of raw) {
    if (resolveRowRegion(r) !== code) continue;
    if (isBlockedCompany(r.company)) continue;
    const matched = matchCompany(r.company, cfg.watchlist);
    if (!matched) continue;
    if (isFullTimeRole({ employmentType: r.employment_type })) continue;
    const stipend = formatStipend({
      min: r.stipend_min, max: r.stipend_max, currency: r.stipend_currency, period: r.stipend_period,
    }) || r.salary_text || null;
    history.push({
      id: String(r.job_id),
      employer: matched,
      title: String(r.title ?? ''),
      firstSeen: Number(r.first_seen_at) || 0,
      postedAt: Number(r.posted_at) || null,
      ats: String(r.job_id).startsWith('ats:'),
      stated: Boolean(stipendText({ stipend })),
      monthlyInr: (r.stipend_currency === 'INR' && r.stipend_period === 'month' && Number(r.stipend_min) > 0) ? Number(r.stipend_min) : null,
      applicants: String(r.job_id).startsWith('ats:') ? null : applicantCount(r.applicants),
      city: foldCity(canonicalCity(r.location) || ''),
      mode: String(r.workplace_type ?? '').toLowerCase().replace(/[^a-z]/g, ''),
      skills: safeList(r.skills),
    });
  }
  history.sort((a, b) => a.firstSeen - b.firstSeen);
  const rows = history.filter((r) => r.firstSeen > since && r.firstSeen <= now);
  const trackedSince = history.length ? history[0].firstSeen : null;
  return { region: code, rows, history, since, now, days, trackedSince };
}

/* One name per city for a COUNT. canonicalCity strips trailing noise for a
   facet slug and deliberately leaves the spelling alone; a ranked list that
   shows Bengaluru and Bangalore as two entries is wrong in a way a reader
   spots at once. Only the spellings the store actually holds. */
const CITY_FOLD = { bangalore: 'Bengaluru', 'bangalore urban': 'Bengaluru', 'bengaluru urban': 'Bengaluru', 'bangalore rural': 'Bengaluru', gurgaon: 'Gurugram', 'new delhi': 'Delhi', bombay: 'Mumbai', 'navi mumbai': 'Mumbai', 'greater noida': 'Noida', 'thane': 'Mumbai', 'secunderabad': 'Hyderabad' };
export function foldCity(city) {
  const k = String(city ?? '').trim().toLowerCase();
  return CITY_FOLD[k] ?? String(city ?? '').trim();
}

function safeList(json) {
  try { const v = JSON.parse(json || '[]'); return Array.isArray(v) ? v.map(String) : []; } catch { return []; }
}

